#!/usr/bin/env bash
#
# Installs a self-contained MinGW-w64 toolchain for the
# x86_64-w64-mingw32 target (the linker + import libraries that
# x86_64-pc-windows-gnu needs to link against the Windows API).
#
# The toolchain is extracted into ./.mingw-w64 and ./.cargo/config.toml
# is regenerated to point rustc at the correct linker and dlltool.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(dirname "$SCRIPT_DIR")"
PREFIX="$PROJECT_DIR/.mingw-w64"
ROOT="$PREFIX/root"
DEBS="$PREFIX/debs"

ARCH="$(uname -m)"
case "$ARCH" in
  aarch64 | arm64)
    HOST_PKG_ARCH=arm64
    BASE="http://ports.ubuntu.com/ubuntu-ports"
    ;;
  x86_64 | amd64)
    HOST_PKG_ARCH=amd64
    BASE="http://archive.ubuntu.com/ubuntu"
    ;;
  *)
    echo "error: unsupported host architecture: $ARCH" >&2
    exit 1
    ;;
esac

# Ubuntu 24.04 (noble) MinGW-w64 packages providing the x86_64-w64-mingw32
# runtime, linker and platform import libraries.
BINUTILS_V="2.41.90.20240122-1ubuntu1+11.4"
GCC_V="13.2.0-6ubuntu1+26.1"
MINGW_V="11.0.1-3build1"

PKGS=(
  "b/binutils-mingw-w64/binutils-mingw-w64-x86-64_${BINUTILS_V}_${HOST_PKG_ARCH}.deb"
  "g/gcc-mingw-w64/gcc-mingw-w64-x86-64-posix_${GCC_V}_${HOST_PKG_ARCH}.deb"
  "g/gcc-mingw-w64/gcc-mingw-w64-x86-64-posix-runtime_${GCC_V}_${HOST_PKG_ARCH}.deb"
  "g/gcc-mingw-w64/gcc-mingw-w64-base_${GCC_V}_${HOST_PKG_ARCH}.deb"
  "m/mingw-w64/mingw-w64-x86-64-dev_${MINGW_V}_all.deb"
  "m/mingw-w64/mingw-w64-common_${MINGW_V}_all.deb"
)

mkdir -p "$DEBS" "$ROOT"
for pkg in "${PKGS[@]}"; do
  deb="$DEBS/$(basename "$pkg")"
  if [ ! -f "$deb" ]; then
    echo "downloading $(basename "$pkg")"
    curl -fL --retry 3 -o "$deb" "$BASE/pool/universe/$pkg"
  fi
  dpkg-deb -x "$deb" "$ROOT"
done

# rustc resolves the default linker by the bare target triple name; the
# Ubuntu package only ships the suffixed posix driver.
ln -sf x86_64-w64-mingw32-gcc-posix "$ROOT/usr/bin/x86_64-w64-mingw32-gcc"

LINKER="$ROOT/usr/bin/x86_64-w64-mingw32-gcc"
DLLTOOL="$ROOT/usr/bin/x86_64-w64-mingw32-dlltool"
test -x "$LINKER"
test -x "$DLLTOOL"

if command -v rustup >/dev/null 2>&1; then
  rustup target add x86_64-pc-windows-gnu
fi

mkdir -p "$PROJECT_DIR/.cargo"
cat > "$PROJECT_DIR/.cargo/config.toml" <<EOF
# Generated by scripts/setup-mingw-w64.sh -- edit that script, not this file.
[target.x86_64-pc-windows-gnu]
linker = "$LINKER"
rustflags = [
  "-C", "dlltool=$DLLTOOL",
]
EOF

echo "MinGW-w64 installed under $PREFIX"
echo "Build with: cargo build --target x86_64-pc-windows-gnu"
