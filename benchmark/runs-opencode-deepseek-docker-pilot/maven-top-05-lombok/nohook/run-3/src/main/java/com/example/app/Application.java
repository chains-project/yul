package com.example.app;

import java.math.BigDecimal;

import com.example.app.model.Product;
import com.example.app.model.User;

import lombok.extern.slf4j.Slf4j;

/**
 * Small entry point showing the Lombok-generated API in action.
 * @Slf4j injects a private static final org.slf4j.Logger "log".
 */
@Slf4j
public class Application {

    public static void main(String[] args) {
        User user = User.builder()
                .id(1L)
                .username("ada")
                .email("ada@example.com")
                .active(true)
                .build();
        // setter generated by @Data
        user.setEmail("ada.lovelace@example.com");
        log.info("user={}", user);

        Product product = Product.builder()
                .sku("SKU-1")
                .name("Keyboard")
                .price(new BigDecimal("49.99"))
                .quantity(3)
                .build();
        // wither generated by @With (returns a copy)
        Product discounted = product.withPrice(new BigDecimal("39.99"));
        log.info("product={}", product);
        log.info("discounted={}", discounted);
    }
}
